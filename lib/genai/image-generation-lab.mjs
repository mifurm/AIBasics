import { decodePng, encodePng, pngChunks, meanAbsoluteDifference, resizeBox } from '../media/png.mjs';
import { analyzeColorLayout, layoutChecks, differingPixelFraction, c2paLabels } from '../media/color-layout.mjs';
import { experimentResult, table, image, text } from './contract.mjs';
import { sha256 } from './artifacts.mjs';

export const specificPrompt = 'A flat 2D vector illustration on a plain white background: one solid red circle on the left half and one solid blue square on the right half. No other objects, no text, no shadows.';
export const vaguePrompt = 'A cool picture of some shapes.';
const describePrompt = 'In one sentence, describe exactly what is in this picture, including the colors, the shapes, and where each shape is.';
const labels = [
  'The specific prompt, first sample',
  'The same specific prompt, second sample',
  'A vague prompt leaves the choices to the model',
];
export const STORE_LIMIT_BYTES = 900_000;

const pct = value => `${(100 * value).toFixed(1)}%`;
const dataUrl = png => `data:image/png;base64,${png.toString('base64')}`;

async function describe(ctx, png) {
  const response = await ctx.azure.chat({
    model: ctx.config.standardDeployment, temperature: 0, max_tokens: 90,
    messages: [{ role: 'user', content: [{ type: 'text', text: describePrompt }, { type: 'image_url', image_url: { url: dataUrl(png), detail: 'low' } }] }],
  });
  return { description: response.choices[0].message.content?.trim() ?? '', call: response.call };
}

export function galleryCopy(png, decoded) {
  if (png.length <= STORE_LIMIT_BYTES) return { data: png, downscaled: false };
  const small = resizeBox(decoded, 512, 512);
  return { data: encodePng({ width: 512, height: 512, data: small.data, channels: 4 }), downscaled: true };
}

export function inspectGeneratedPng(png) {
  const decoded = decodePng(png);
  const chunks = pngChunks(png);
  const provenance = chunks.find(chunk => chunk.type === 'caBX');
  return {
    decoded, analysis: analyzeColorLayout(decoded),
    chunkTypes: [...new Set(chunks.map(chunk => chunk.type))],
    provenance: provenance ? { chunk: 'caBX', bytes: provenance.length, labels: c2paLabels(provenance.data) } : null,
  };
}

export const imageGenerationLab = {
  id: '32-image-generation', title: 'From prompt to pixels', minutes: 12, series: 'genai',
  concept: 'An image model turns a text prompt into pixels. The prompt guides the result but does not fully control it: the same prompt gives different images, and unspecified details are chosen by the model. You can measure what you asked for.',
  question: 'Which parts of the request did the picture honor, which did it ignore, and how would you check that without trusting your eyes alone?',
  caveat: 'Two samples are not a statistical test, and simple color checks only test simple prompts. A model that describes an image can be wrong too. Generated images may carry provenance metadata; this does not prove how they were used.',
  exercise: 'Change specificPrompt in lib/genai/image-generation-lab.mjs to ask for a green triangle above a yellow circle, then update the color checks in lib/media/color-layout.mjs.',
  cases: labels.map(label => ({ label, experiment: true })),
  async run(ctx) {
    const samples = [];
    let firstDecoded;
    for (const [index, prompt] of [specificPrompt, specificPrompt, vaguePrompt].entries()) {
      const started = performance.now();
      const generated = await ctx.azure.image({ prompt, size: '1024x1024', quality: 'low' });
      const inspected = inspectGeneratedPng(generated.png);
      if (inspected.decoded.width !== 1024 || inspected.decoded.height !== 1024) throw new Error('Azure returned an unexpected image size.');
      const stored = galleryCopy(generated.png, inspected.decoded);
      const artifact = ctx.artifacts.add({
        id: ['specific-sample-one', 'specific-sample-two', 'vague-sample'][index], extension: 'png', data: stored.data,
        description: `${labels[index]}: image generated by ${ctx.azure.names.image} at 1024 by 1024 pixels and low quality${stored.downscaled ? '; this gallery copy is re-encoded at 512 by 512 pixels to keep the page light' : ''}.`,
      });
      const originalSha256 = sha256(generated.png);
      const seen = await describe(ctx, generated.png);
      samples.push({ originalSha256 });
      const { analysis, provenance } = inspected;
      const specific = index < 2;
      const checks = specific ? layoutChecks(analysis) : [];
      const comparison = index === 1 ? { meanAbsoluteDifference: meanAbsoluteDifference(firstDecoded, inspected.decoded), differingPixels: differingPixelFraction(firstDecoded, inspected.decoded), identicalBytes: samples[0].originalSha256 === originalSha256 } : null;
      if (index === 0) firstDecoded = inspected.decoded;
      const provenanceText = provenance ? `The PNG the model returned contains a ${provenance.chunk} chunk (${provenance.bytes} bytes), the container PNG uses for C2PA Content Credentials${provenance.labels.length ? `. It includes: ${provenance.labels.join(', ')}` : ''}. ${stored.downscaled ? 'This gallery copy was re-encoded and no longer carries it.' : 'It travels with the file unless something strips it.'}` : 'No caBX (C2PA Content Credentials) chunk was found in this PNG.';
      const reported = generated.usage;
      ctx.addResult(experimentResult({
        label: labels[index], startedAt: started, calls: [generated.call, seen.call], artifacts: [artifact],
        summary: `Prompt: "${prompt}" Sent to ${ctx.azure.names.image} at 1024x1024, quality low. Then GPT-4o (low image detail) was asked: "${describePrompt}"`,
        parameters: { prompt, size: '1024x1024', quality: 'low', output_format: 'png' },
        output: [`Image: ${inspected.decoded.width}x${inspected.decoded.height}, ${generated.png.length} bytes${stored.downscaled ? ` (gallery copy: ${artifact.bytes} bytes at 512x512)` : ''}.`,
          specific ? `Pixel checks matched ${checks.filter(check => check.passed).length} of ${checks.length} targets.` : `Dominant colors: ${analysis.dominantColors.map(color => `${color.name} ${pct(color.fraction)}`).join(', ')}.`,
          comparison ? `Versus sample one: mean pixel difference ${comparison.meanAbsoluteDifference.toFixed(1)} of 255; ${pct(comparison.differingPixels)} of pixels differ visibly.` : '',
          `GPT-4o describes it as: ${seen.description}`].filter(Boolean).join('\n'),
        measurements: { analysis, checks, provenance, chunkTypes: inspected.chunkTypes, description: seen.description, comparison, imageUsage: reported ?? null, original: { bytes: generated.png.length, sha256: originalSha256, galleryCopyDownscaled: stored.downscaled } },
        display: [
          image(artifact, `${labels[index]} (generated by ${ctx.azure.names.image}).`, `Generated image for the prompt: ${prompt}`),
          ...(specific ? [table('Pixel measurements against the request', ['Check', 'Result', 'Measured'], checks.map(check => [check.name, check.passed ? 'MATCHED' : 'NOT MATCHED', check.detail]))] :
            [table('Colors the model chose to use', ['Color', 'Share of pixels'], analysis.dominantColors.map(color => [color.name, pct(color.fraction)]))]),
          ...(comparison ? [table('Same prompt, two samples', ['Measurement', 'Value'], [['Mean pixel difference (0-255)', comparison.meanAbsoluteDifference.toFixed(1)], ['Pixels differing visibly', pct(comparison.differingPixels)], ['Byte-identical files', comparison.identicalBytes ? 'yes' : 'no']])] : []),
          table('What the image API reported', ['Quantity', 'Value'], [
            ['Prompt (text) tokens in', reported?.input_tokens ?? 'not reported'], ['Image tokens out', reported?.output_tokens_details?.image_tokens ?? 'not reported'],
            ['Total tokens out', reported?.output_tokens ?? 'not reported'], ['Generation time (ms)', generated.call.latencyMs], ['File size (bytes)', generated.png.length]]),
          text(`An independent check: GPT-4o was shown this image and wrote: "${seen.description}"`),
          text(provenanceText),
        ],
      }));
    }
  },
  evaluate(results) {
    const check = (name, passed, detail) => ({ name, passed: Boolean(passed), detail });
    const [first, second, vague] = results;
    return [
      check('Three images were generated at the requested size', results.length === 3 && results.every(result => result.measurements.analysis.width === 1024 && result.measurements.analysis.height === 1024 && result.measurements.original.bytes > 1_000), results.map(result => `${result.measurements.original.bytes} bytes`).join(', ')),
      check('Every image call reports usage and every description is non-empty', results.every(result => Number.isInteger(result.apiCalls[0].usage?.total_tokens) && result.measurements.description.length > 10), results.map(result => `${result.apiCalls[0].usage?.total_tokens} image tokens`).join(', ')),
      check('The two specific samples were compared pixel by pixel', Number.isFinite(second.measurements.comparison?.meanAbsoluteDifference) && Number.isFinite(second.measurements.comparison?.differingPixels), `Mean difference ${second.measurements.comparison?.meanAbsoluteDifference.toFixed(1)} of 255; identical bytes: ${second.measurements.comparison?.identicalBytes}.`),
      check('Target checks are recorded for the specific prompt, not used to hide failures', [first, second].every(result => result.measurements.checks.length === 6),
        [first, second].map((result, index) => `Sample ${index + 1}: ${result.measurements.checks.filter(item => item.passed).length}/6 matched`).join('; ')),
      check('The vague prompt was analysed without specific targets', vague.measurements.checks.length === 0 && vague.measurements.analysis.dominantColors.length > 0, vague.measurements.analysis.dominantColors.map(item => item.name).join(', ')),
    ];
  },
};
